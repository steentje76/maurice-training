/* #504: structural native security gate. THIS IS NOT Android device evidence.
 * Native compile & instrumentation tests are separate required gates.
 */
'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.join(__dirname,'..');
const java=path.join(root,'android/app/src/main/java/com/trainingskompas/app');
const read=f=>fs.readFileSync(path.join(java,f),'utf8');
const integrity=JSON.parse(fs.readFileSync(path.join(root,'android/app/src/main/assets/tk-movekit-integrity.json'),'utf8'));
const manifest=fs.readFileSync(path.join(root,'android/app/src/main/AndroidManifest.xml'),'utf8');
const gradle=fs.readFileSync(path.join(root,'android/app/build.gradle'),'utf8');
const activity=read('MainActivity.java');
const vault=read('TkMediaVault.java');
const plugin=read('TkOfflineMediaPlugin.java');
const player=read('TkOfflineVideoPlayer.java');
const reader=read('TkMediaDataSource.java');
const appfiles=fs.readdirSync(path.join(root,'android/app/src/main/assets'));
const artifacts=fs.readdirSync(path.join(root,'android/app/src/main/java/com/trainingskompas/app'));
let passed=0;const ok=(cond,reason)=>{assert.ok(cond,reason);passed++;};
ok(integrity.schema==='tk-secure-media-integrity/1','strict integrity schema');
ok(integrity.items.length===808,'226 V1 + 582 V2 digests embedded');
ok(integrity.items.filter(x=>x.version==='v1').length===226,'V1 remains immutable');
ok(integrity.items.filter(x=>x.version==='v2').length===582,'V2 staged without switch');
ok(new Set(integrity.items.map(x=>x.catalogId+':'+x.version)).size===808,'no duplicate manifest identities');
ok(integrity.items.every(x=>/^[0-9a-f]{64}$/.test(x.sha256)&&x.bytes>0&&x.bytes<=33554432),'only validated hashes & bounded size');
ok(appfiles.every(x=>!/\.(mp4|webm|mov|png)$/.test(x)),'no licensed media assets in APK native directory');
ok(/allowBackup="false"/.test(manifest),'backup disabled');
ok(/android\.permission\.ACCESS_NETWORK_STATE/.test(manifest),'Wi-Fi/metered detection permission');
ok(!/no-backup-path/.test(fs.readFileSync(path.join(root,'android/app/src/main/res/xml/file_paths.xml'),'utf8')),'no FileProvider export of secure storage');
ok(/registerPlugin\(TkOfflineMediaPlugin\.class\)/.test(activity),'registered before superclass');
ok(/Build\.VERSION\.SDK_INT >= android\.os\.Build\.VERSION_CODES\.M/.test(activity),'Android API22 does not register API23-only media classes');
ok(/BuildConfig\.DEBUG/.test(plugin),'staged only in DEBUG builds');
ok(/buildFeatures\s*\{\s*buildConfig true\s*\}/.test(gradle),'BuildConfig debug/release difference available');
ok(/getNoBackupFilesDir\(\)/.test(vault),'isolated no-backup private storage');
ok(/"AndroidKeyStore"/.test(vault)&&/setKeySize\(256\)/.test(vault),'Android hardware/software keystore AES256');
ok(/"AES\/GCM\/NoPadding"/.test(vault)&&/updateAAD\(/.test(vault),'authenticated encryption and bound AAD');
ok(/MessageDigest\.getInstance\("SHA-256"\)/.test(vault)&&/MEDIA_INTEGRITY_FAILED/.test(vault),'verify complete stream digest before commit');
ok(/\.partial-/.test(vault)&&/stage\.renameTo\(target\)/.test(vault),'staging + atomic finalization');
ok(/250L\*1024L\*1024L/.test(vault),'quota 250 MiB');
ok(/ks\.deleteEntry\(name\)/.test(vault),'revoke account key on logout');
ok(/class TkMediaDataSource extends MediaDataSource/.test(reader),'no temporary MP4 required');
ok(/vault\.readChunk\(/.test(reader)&&/Arrays\.fill\(plaintext/.test(reader),'seekable in-memory decryption cleared after use');
ok(/setDataSource\(source\)/.test(player),'native player uses encrypted data source');
ok(/FLAG_SECURE/.test(player),'native playback screen capture guard');
ok(/new URL\(raw\)/.test(plugin)&&/TRUSTED_HOST/.test(plugin)&&/setInstanceFollowRedirects\(false\)/.test(plugin),'signed URL and redirect strict checks');
ok(/hasTransport\(NetworkCapabilities\.TRANSPORT_WIFI\)/.test(plugin),'Wi-Fi preferred');
ok(/wifi\.openConnection\(url\)/.test(plugin),'Wi-Fi-only download is network-pinned, never falls back to cellular');
ok(player.indexOf('w.setFlags(WindowManager.LayoutParams.FLAG_SECURE')<player.indexOf('dialog.show()'),'screen protected before first video frame');
ok(/allowMetered/.test(plugin)&&/WIFI_REQUIRED/.test(plugin),'metered network requires explicit choice');
ok(/logoutAndWipe/.test(plugin)&&/vault\(\)\.clearOwner\(owner\)/.test(plugin),'wipe encrypted files + key on logout');
ok(!/@PluginMethod[^{]*void\s+(readBytes|export|share|downloadPlain)\s*\(/.test(plugin),'no raw video interface for JS');
ok(!/new FileOutputStream.*\.mp4/.test(vault),'no cleartext mp4 writes');
ok(artifacts.includes('TkMediaIntegrity.java')&&artifacts.includes('TkMediaVault.java'),'native core included');
console.log('Native MoveKit staging security guard: '+passed+' PASS (static; physical Android still required)');
