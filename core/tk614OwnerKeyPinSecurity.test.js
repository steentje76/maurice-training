'use strict';
// TK614 public pin only. No access to DPAPI/private signing material or real user accounts.
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..');
const R=require('../tools/tk614_original226_admin_release.cjs');
const L=require('./tk504BatchReleaseLedger.js');
const P=require('../tools/tk614_original226_review_packet.cjs');
const D=require('../tools/tk614_original226_owner_decision.cjs');
const gates=require('../docs/generated/MOVEKIT_V2_RELEASE_GATES.json');
const pin='9a4e3f7ee3cab1792fcc00efca3992c10bb251c0840f47c0a0a224106f280c63';
let checks=0;
const eq=(a,b,msg)=>{assert.deepEqual(a,b,msg);checks++;};
const ok=(v,msg)=>{assert.ok(v,msg);checks++;};
eq(R.TRUSTED_OWNER_KEY_SHA256,[pin],'only the expected Ed25519 public SPKI SHA256 trusted');
ok(Object.isFrozen(R.TRUSTED_OWNER_KEY_SHA256),'trusted public pins immutable');
ok(/^[0-9a-f]{64}$/.test(pin),'sha256 lowercase');
eq(R.original226ReleaseRecordProblems(gates),[],'separate 226 FK-only owner evidence valid');
eq(R.mediaGateProblems(gates),[],'media release remained valid');
eq(R.activationBlockers(gates),[],'pin plus evidence unlocks eligibility checks only, not a signed approval');
eq(L.releasedScope(gates).new_count,356,'356 existing media released independently');
eq(gates.released_batches.length,15,'original 15 batches unchanged');
eq(gates.entries.length,1164,'original media entries unchanged');
eq(gates[P.RECORD_KEY].media_grants,0,'zero additional media grants');
eq(gates[P.RECORD_KEY].media_access,'NOT_RELEASED','no media release from FK approval');
eq(D.repoOwnerDecision().limitations.signed_cryptographic_activate,false,'no owner signature in decision');
const code=fs.readFileSync(path.join(root,'tools','tk614_original226_admin_release.cjs'),'utf8');
ok(code.includes('verifySignature(a,opts.trustedOwnerKeySha256'), 'activation still verifies owner signature');
ok(code.includes('crypto.verify(null,Buffer.from(a.approval_sha256'), 'signature cryptographically verified');
ok(code.includes('ACTIVATION_SIGNATURE_REQUIRED'), 'unsigned activation rejected');
ok(!/BEGIN (?:RSA |EC |OPENSSH )?PRIVATE KEY/.test(code),'no private PEM committed in admin source');
const guide=fs.readFileSync(path.join(root,'docs','TK614_OWNER_ED25519_PUBLIC_KEY_PIN_20261109.md'),'utf8');
ok(guide.includes(pin),'public key fingerprint documented');
ok(guide.includes('geen')&&guide.includes('signatuur'),'no signed release claimed in documentation');
console.log('TK614 owner Ed25519 public pin: '+checks+' assertions PASS; synthetic signer refused by admin tests, no private key and no production activation');
